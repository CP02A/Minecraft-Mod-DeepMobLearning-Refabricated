package dev.nathanpb.dml.modular_armor.mixin;

import dev.nathanpb.dml.modular_armor.effects.PiglinTruceEffect;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.monster.piglin.PiglinAi;
import net.minecraft.world.entity.player.Player;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(PiglinAi.class)
public class PiglinBrainMixin {

    // Piglin Truce: piglins treat the player as if they wore gold
    @Inject(method = "isWearingSafeArmor", at = @At("RETURN"), cancellable = true)
    private static void dml$piglinTruce(LivingEntity entity, CallbackInfoReturnable<Boolean> cir) {
        if (entity instanceof Player player && !cir.getReturnValue()) {
            InteractionResult result = PiglinTruceEffect.Companion.trigger(player);

            if (result == InteractionResult.FAIL) {
                cir.setReturnValue(true);
            }
        }
    }

}

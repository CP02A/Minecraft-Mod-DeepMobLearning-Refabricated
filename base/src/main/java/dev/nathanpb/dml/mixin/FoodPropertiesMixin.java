package dev.nathanpb.dml.mixin;

import dev.nathanpb.dml.event.VanillaEvents;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.food.FoodProperties;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.component.Consumable;
import net.minecraft.world.level.Level;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** Food is eaten (before 1.20.5 this was LivingEntity#eatFood). The stack is not shrunk yet. */
@Mixin(FoodProperties.class)
public class FoodPropertiesMixin {

    @Inject(at = @At("HEAD"), method = "onConsume")
    private void dml$onEat(Level world, LivingEntity user, ItemStack stack, Consumable consumable, CallbackInfo ci) {
        VanillaEvents.INSTANCE.getLivingEntityEatEvent()
                .invoker()
                .invoke(user, stack);
    }
}
